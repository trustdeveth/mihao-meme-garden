// Compile the contracts with Foundry and save what the game needs:
//   chain/artifacts/<Name>.json   ABI and bytecode, used to deploy (so a deploy machine does not need Foundry)
//   shared/src/chain/abi.js       the ABIs the server and browser use
// Run after changing anything in chain/contracts: npm run chain:build
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
execFileSync(process.env.FORGE ?? 'forge', ['build', '--force'], { cwd: resolve(ROOT, 'chain'), stdio: 'inherit' });

mkdirSync(resolve(ROOT, 'chain/artifacts'), { recursive: true });
const abis = {};
// GardenRewards is the only contract that gets deployed; the two tokens exist for the tests
for (const name of ['GardenRewards', 'TestToken', 'TaxToken']) {
  const out = JSON.parse(readFileSync(resolve(ROOT, `chain/out/${name}.sol/${name}.json`), 'utf8'));
  abis[name] = out.abi;
  writeFileSync(resolve(ROOT, `chain/artifacts/${name}.json`), `${JSON.stringify({ contractName: name, abi: out.abi, bytecode: out.bytecode.object }, null, 1)}\n`);
}
writeFileSync(resolve(ROOT, 'shared/src/chain/abi.js'), `// Generated by tools/chain/build.mjs from chain/contracts. Do not edit by hand.
export const TOKEN_ABI = Object.freeze(${JSON.stringify(abis.TestToken)});
export const REWARDS_ABI = Object.freeze(${JSON.stringify(abis.GardenRewards)});
`);
console.log('Wrote chain/artifacts and shared/src/chain/abi.js');
